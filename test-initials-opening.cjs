'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const engine = require('./template-engine.js');
const adapter = require('./invitation-document-adapter.js');
const { buildPublicationCandidate } = require('./lib/publication-candidate.cjs');
const { publicPresentation } = require('./lib/public-review.cjs');

const config = structuredClone(engine.defaultConfig);
config.eventType = 'boda'; config.name = 'Test couple'; config.brideName = 'Mara'; config.groomName = 'Fer';
config.monogram = 'M & F'; config.waxSeal = { enabled: true, openingStyle: 'initials', customImage: 'assets/seal.png' };
const opening = engine.generateHTML(config, 'vino').match(/<div id="waxSealCurtain"[\s\S]*?<!-- Capa de Fondo/)[0];
assert.match(opening, /<button[^>]+id="btnBreakWaxSeal"/, 'Initials are a keyboard-accessible opening button');
assert.match(opening, /class="opening-initials font-names"/, 'Initials use the invitation names font');
assert.match(opening, /<span class="opening-initial-line">M<\/span><span class="opening-initial-line">&amp;<\/span><span class="opening-initial-line">F<\/span>/, 'Initials are stacked like the reference, without names');
assert.match(opening, /class="opening-initials-curtain /, 'Initials opening has its own background');
assert.match(opening, /class="paper-grain-overlay opening-paper-grain" aria-hidden="true"/, 'Paper texture reuses the existing decoration');
assert.doesNotMatch(opening, /<svg|<img|Toca el sello|Mara|Fer/, 'No seal, duplicate full names, or seal hint');
assert.match(opening, /opening-initials font-names[\s\S]*?class="opening-announcement">Tenemos una noticia…<\/span>[\s\S]*?class="opening-action-hint">Haz click<\/span>[\s\S]*?<\/button>/, 'Announcement and hint appear below initials inside the opening button');
const html = engine.generateHTML(config, 'vino');
assert.match(html, /\.opening-initials-curtain \{ --opening-ink: #f7f6ec; background: #0D1524; \}/, 'Ivory initials on the existing navy palette');
assert.match(html, /font-size: clamp\(3rem, 6vw, 4rem\)/, 'Medium responsive size: 48–64px');
assert.match(html, /\.opening-initials-button:focus-visible/, 'Visible keyboard focus');
for (const mode of [undefined, 'seal', 'unexpected']) {
  config.waxSeal.openingStyle = mode;
  assert.match(engine.generateHTML(config, 'vino'), /alt="Sello de Cera Personalizado"/, 'Existing invitations retain seals');
}
config.waxSeal.openingStyle = 'initials'; config.waxSeal.enabled = false;
assert.doesNotMatch(engine.generateHTML(config, 'vino'), /<div id="waxSealCurtain"/, 'Disabled opening remains disabled');
config.waxSeal.enabled = true;
config.waxSeal.customImage = '';
config.story.enabled = false; config.giftRegistry.enabled = false;
config.lodging.enabled = false; config.sharedAlbum.enabled = false;
config.whatsappNumber = ''; config.whatsappHosts = [];
config.eventDateISO = '2027-11-14T18:00'; config.eventDateLabel = ''; config.eventDateShort = '';
const doc = adapter.fromLegacyTemplateConfig(config, {projectId:'20000000-0000-4000-8000-000000000002',revision:1}).document;
assert.equal(adapter.toLegacyTemplateConfig(doc).waxSeal.openingStyle, 'initials', 'Cloud roundtrip preserves mode');
const candidate = buildPublicationCandidate({documentId:'30000000-0000-4000-8000-000000000003',document:doc});
const publicConfig = publicPresentation({slug:'test-couple',document:doc,candidate});
assert.equal(publicConfig.waxSeal.openingStyle, 'initials', 'Published presentation retains mode');
assert.match(engine.generateHTML(publicConfig, 'vino'), /class="opening-initial-line">M/);
config.monogram = '<img src=x onerror=alert(1)>';
const hostileOpening = engine.generateHTML(config, 'vino').match(/<div id="waxSealCurtain"[\s\S]*?<!-- Capa de Fondo/)[0];
assert.doesNotMatch(hostileOpening, /<img/, 'Initials are encoded as text, not executable markup');
assert.match(hostileOpening, /&lt;img/);
const handler = html.match(/const waxCurtain = [\s\S]*?(?=\/\/ 5\. Reproductor)/)[0];
const curtain = {style:{},remove(){this.removed=true;}};
const button = {addEventListener(type,fn){this[type]=fn;}};
const audio = {paused:true,play(){this.played=true;return Promise.resolve();}};
vm.runInNewContext(handler,{document:{getElementById:id=>({waxSealCurtain:curtain,btnBreakWaxSeal:button,musicAudio:audio}[id])},setTimeout:fn=>fn()});
button.click();
assert.equal(curtain.removed,true); assert.equal(audio.played,true, 'Opening gesture preserves music start');
const source = fs.readFileSync('app.js','utf8');
const binding = source.match(/function setupOpeningStyleControl\(\) \{[\s\S]*?\n\}/);
assert.ok(binding, 'Studio mode binding exists');
const control = { addEventListener(type,fn) { this[type]=fn; } };
const sandbox = {document:{getElementById:()=>control},currentConfig:{},schedulePreviewUpdate(){sandbox.updated=true;}};
vm.runInNewContext(binding[0]+'\nsetupOpeningStyleControl();',sandbox);
control.change({target:{value:'initials'}});
assert.equal(sandbox.currentConfig.waxSeal.openingStyle,'initials'); assert.equal(sandbox.updated,true);
control.change({target:{value:'unexpected'}});
assert.equal(sandbox.currentConfig.waxSeal.openingStyle,'seal');
assert.match(fs.readFileSync('invitacion-estudio.html','utf8'), /<label for="selectOpeningStyle">/);
console.log('Initials opening: render, isolation, medium typography, keyboard semantics, persistence and Studio binding passed.');
